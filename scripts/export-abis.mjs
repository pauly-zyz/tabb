#!/usr/bin/env node
// Copies ABIs from Foundry artifacts (contracts/out) into web/src/abi/index.ts.
// Run after `forge build`:  node scripts/export-abis.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "contracts", "out");
const contracts = {
  tabbPoolAbi: "TabbPool",
  agentCreditManagerAbi: "AgentCreditManager",
  agentCreditScoreAbi: "AgentCreditScore",
  agentRiskConfigAbi: "AgentRiskConfig",
  ownerStakeVaultAbi: "OwnerStakeVault",
  payeeRegistryAbi: "PayeeRegistry",
  policyAccountAbi: "PolicyAccount",
  repaymentSplitterAbi: "RepaymentSplitter",
  mockUsdgAbi: "MockUSDG",
  mockIdentityRegistryAbi: "MockERC8004IdentityRegistry",
};

let src = "// AUTO-GENERATED by scripts/export-abis.mjs — do not edit by hand.\n\n";
for (const [name, contract] of Object.entries(contracts)) {
  const artifact = JSON.parse(readFileSync(join(out, `${contract}.sol`, `${contract}.json`), "utf8"));
  src += `export const ${name} = ${JSON.stringify(artifact.abi)} as const;\n\n`;
}
writeFileSync(join(root, "web", "src", "abi", "index.ts"), src);
console.log(`wrote ${Object.keys(contracts).length} ABIs to web/src/abi/index.ts`);
