#!/usr/bin/env node
// Writes the addresses from contracts/deployments/<chainId>.json (+ .yield.json) into config/addresses.ts.
//   node scripts/sync-addresses.mjs <chainId> [--mocks] [--stable USDC]
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const chainId = process.argv[2];
const mocks = process.argv.includes("--mocks");
const si = process.argv.indexOf("--stable");
const stable = si > 0 ? process.argv[si + 1] : undefined;
if (!chainId) throw new Error("usage: sync-addresses.mjs <chainId> [--mocks]");

const dep = JSON.parse(readFileSync(join(root, "contracts/deployments", `${chainId}.json`), "utf8"));
const yieldPath = join(root, "contracts/deployments", `${chainId}.yield.json`);
const y = existsSync(yieldPath) ? JSON.parse(readFileSync(yieldPath, "utf8")) : undefined;

const keys = [
  "usdg",
  "identityRegistry",
  "interestRateModel",
  "pool",
  "registryAdapter",
  "riskConfig",
  "stakeVault",
  "creditScore",
  "payeeRegistry",
  "agentCreditManager",
];
let entry = `  ${chainId}: {\n    // generated by scripts/sync-addresses.mjs from contracts/deployments/${chainId}.json\n`;
for (const k of keys) entry += `    ${k}: "${dep[k]}",\n`;
if (dep.demoProvider) entry += `    demoProvider: "${dep.demoProvider}",\n`;
entry += `    mocks: ${mocks},\n`;
if (stable) entry += `    stableSymbol: "${stable}",\n`;
if (y) {
  entry += "    yield: {\n";
  for (const k of ["pool", "oracle", "risk", "tabManager", "harvester", "liquidator", "shareAdapter", "ytAdapter", "vault", "yieldToken", "ytFeed"]) {
    if (y[k] && y[k] !== "0x0000000000000000000000000000000000000000") entry += `      ${k}: "${y[k]}",\n`;
  }
  entry += "    },\n";
}
entry += "  },\n";

const file = join(root, "config/addresses.ts");
let src = readFileSync(file, "utf8");
const start = src.indexOf(`  ${chainId}: {`);
if (start >= 0) {
  // replace existing block (ends at the first line that is exactly "  },")
  const end = src.indexOf("\n  },\n", start) + "\n  },\n".length;
  src = src.slice(0, start) + entry + src.slice(end);
} else {
  const marker = "  // TODO: Robinhood Chain testnet";
  const at = src.indexOf(marker);
  if (at < 0) throw new Error("insertion marker not found");
  src = src.slice(0, at) + entry + src.slice(at);
}
writeFileSync(file, src);
console.log(`config/addresses.ts: wrote chain ${chainId}${y ? " (+ yield)" : ""}`);
